    sidecars: dict[str, SidecarDeployConfig]
    watch_paths: tuple[str, ...]
    database: str | None

    @property
    def is_deployable(self) -> bool:
        return self.strategy != "none"

    @property
    def needs_docker(self) -> bool:
        return self.strategy == "service"

    @property
    def needs_node(self) -> bool:
        return self.type in ("nextjs", "vite", "react", "vue", "angular")

    @property
    def needs_database_migration(self) -> bool:
        return self.database is not None

    @property
    def iac_key(self) -> str:
        """IaC-convention key: backends get -service, frontends get -frontend."""
        if self.kind == "backend":
            return f"{{self.name}}-service"
        elif self.kind == "frontend":
            return f"{{self.name}}-frontend"
        return self.name

    @property
    def has_sidecars(self) -> bool:
        return bool(self.sidecars)


