@dataclass(frozen=True)
class ServiceConfig:
    """Lean service definition from foundry.json.

    v0.5.0: ``scope``, ``stack`` (type/framework/language), ``deploy`` (strategy),
            ``run`` (port/args), ``database`` (inline).
    v0.4.0 compat: ``kind``→stack.type, ``type``→stack.framework, ``role``→scope.
    """
    kind: str | None = None          # stack.type (backend/frontend/package)
    type: str | None = None          # stack.framework (spring-boot, nextjs, etc.)
    role: str | None = None          # scope (public/internal)
    database: str | dict[str, Any] | None = None
    deploy: DeployConfig | None = None

    # --- helper properties ---------------------------------------------------

    @property
    def database_name(self) -> str | None:
        """Logical database name (service name when inline dict, string ref otherwise)."""
        if isinstance(self.database, dict):
            return None  # caller must use the service name as db_name
        return self.database

    @property
    def database_config(self) -> dict[str, Any] | None:
        """Database config dict when declared inline; ``None`` for string refs."""
        return self.database if isinstance(self.database, dict) else None

    @property
    def strategy(self) -> str | None:
        """Deployment strategy from the deploy block."""
        return self.deploy.strategy if self.deploy else None

    @property
    def effective_strategy(self) -> str | None:
        """Deploy block strategy (normalised: ecs→service, s3-static→static)."""
        raw = self.deploy.strategy if self.deploy else None
        if not raw:
            return None
        return {{"ecs": "service", "s3-static": "static"}}.get(raw, raw)

    @classmethod
    def from_dict(cls, data: dict[str, Any]) -> "ServiceConfig":
        # ── Stack resolution ─────────────────────────────────────────
        stack = data.get("stack", {{}})
        if isinstance(stack, dict) and stack:
            stack_type = stack.get("type")
            stack_framework = stack.get("framework")
        else:
            stack_type = data.get("kind")
            stack_framework = data.get("type")

        # ── Scope → role ─────────────────────────────────────────────
        scope = data.get("scope") or data.get("role")

        # ── Deploy block ─────────────────────────────────────────────
        deploy = None
        if "deploy" in data and isinstance(data["deploy"], dict):
            deploy = DeployConfig.from_dict(data["deploy"])
        elif data.get("strategy"):
            # v0.4.0 flat strategy → synthesize a DeployConfig
            deploy = DeployConfig(strategy=data["strategy"])

        return cls(
            kind=stack_type,
            type=stack_framework,
            role=scope,
            database=data.get("database"),
            deploy=deploy,
        )


