def _gen_change_detector(manifest: ProjectManifest, header: str) -> str:
    return f'''{header}
"""Change detector — determines which services need deployment.

Uses git diff to find changed files and maps them to services using
watch paths from the convention engine.
"""

from __future__ import annotations

import json
import logging
import os
import re
import subprocess
from typing import Any

from core.conventions import DeploymentProfile, resolve_all_profiles
from core.manifest_reader import Manifest

logger = logging.getLogger(__name__)


def detect_changes(
    git_before: str,
    git_after: str,
    branch: str,
    force: str = "",
) -> dict[str, Any]:
    """Detect which services changed and need deployment.

    Returns a dict with:
      - services: list of service names that changed
      - environment: resolved environment name
      - has_db_changes: whether any database changelog paths changed
    """
    manifest = Manifest.load()
    environment = manifest.resolve_environment(branch)

    if not environment:
        logger.info(f"ℹ️ Branch '{{branch}}' does not map to any environment — skipping")
        return {{"services": [], "environment": "", "has_db_changes": "false"}}

    profiles = resolve_all_profiles(manifest)

    # Force-deploy specific services
    if force:
        forced = [s.strip() for s in force.split(",") if s.strip()]
        logger.info(f"⚡ Force deploying: {{forced}}")
        return {{
            "services": forced,
            "environment": environment,
            "has_db_changes": str(any(
                profiles.get(s, None) and profiles[s].database for s in forced
            )).lower(),
        }}

    # Get changed files
    changed_files = _get_changed_files(git_before, git_after)
    if not changed_files:
        logger.info("ℹ️ No files changed")
        return {{"services": [], "environment": environment, "has_db_changes": "false"}}

    logger.info(f"📝 {{len(changed_files)}} files changed")

    # Match to services
    affected: list[str] = []
    for name, profile in profiles.items():
        if not profile.is_deployable:
            continue
        for pattern in profile.watch_paths:
            if any(re.match(pattern, f) for f in changed_files):
                affected.append(name)
                break

    # Check for IaC changes (deploys everything)
    ci_dir = manifest.ci.get("iacDir", "ci/iac")
    if any(f.startswith(f"{{ci_dir}}/") for f in changed_files):
        logger.info("🏗️ IaC changes detected — all services will deploy")
        affected = [n for n, p in profiles.items() if p.is_deployable]

    # Check for database changes
    db_paths = [db.get("changelog", "").rsplit("/", 1)[0] for db in manifest.databases.values()]
    has_db_changes = any(
        any(f.startswith(dp) for dp in db_paths if dp)
        for f in changed_files
    )

    logger.info(f"🎯 Affected services: {{affected}}")
    return {{
        "services": affected,
        "environment": environment,
        "has_db_changes": str(has_db_changes).lower(),
    }}


def _get_changed_files(before: str, after: str) -> list[str]:
    """Get list of changed files between two git commits."""
    try:
        result = subprocess.run(
            ["git", "diff", "--name-only", before, after],
            capture_output=True, text=True, check=True,
        )
        return [f.strip() for f in result.stdout.strip().splitlines() if f.strip()]
    except subprocess.CalledProcessError as e:
        logger.warning(f"⚠️ git diff failed: {{e}}")
        return []


def write_github_outputs(result: dict[str, Any]) -> None:
    """Write detection results to GITHUB_OUTPUT if running in Actions."""
    github_output = os.environ.get("GITHUB_OUTPUT")
    if not github_output:
        logger.info("ℹ️ Not in GitHub Actions — printing results to stdout")
        print(json.dumps(result, indent=2))
        return

    with open(github_output, "a") as f:
        f.write(f"services={{json.dumps(result['services'])}}\\n")
        f.write(f"environment={{result['environment']}}\\n")
        f.write(f"has_db_changes={{result['has_db_changes']}}\\n")

    logger.info(f"✅ GitHub outputs written: {{len(result['services'])}} services, env={{result['environment']}}")
'''


