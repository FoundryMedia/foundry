"""Scripts generator — produces the complete ``ci/scripts/`` directory from the manifest.

This module generates every Python file in ``ci/scripts/`` including:

- ``core/`` — manifest reader, convention engine, secrets handler
- ``engines/`` — ECS, S3 static, IaC, and database migration engines
- ``orchestration/`` — change detector, dependency graph, coordinator
- ``deploy.py`` — unified CLI entry point
- ``requirements.txt`` — pinned dependencies

All generated files are self-contained — they do NOT depend on the Foundry CLI
at runtime.  They read ``foundry.json`` directly and resolve deployment profiles
using an embedded copy of the convention engine.
"""

from __future__ import annotations

import shutil
from pathlib import Path
from typing import Any

from foundry_cli.core.project.manifest import ProjectManifest

# ── Header for all generated files ───────────────────────────────────────

_HEADER = '''\
# ════════════════════════════════════════════════════════════════════════════
# GENERATED BY: foundry generate scripts
# Manual edits may break regeneration — edit with intention.
# Regenerate with: foundry generate scripts --clean
# Source: foundry.json (schemaVersion {schema_version})
# ════════════════════════════════════════════════════════════════════════════
'''


def generate_scripts(manifest: ProjectManifest, output_dir: Path, *, clean: bool = False) -> list[Path]:
    """Generate the complete ``ci/scripts/`` directory tree.

    Args:
        manifest: A loaded ``ProjectManifest``.
        output_dir: Absolute path to the target ``ci/scripts/`` directory.
        clean: If ``True``, delete and recreate the directory from scratch.

    Returns:
        List of all generated file paths.
    """
    schema_version = manifest.data.get("schemaVersion", "0.3.0")
    header = _HEADER.format(schema_version=schema_version)

    if clean and output_dir.exists():
        shutil.rmtree(output_dir)

    output_dir.mkdir(parents=True, exist_ok=True)

    generated: list[Path] = []

    # Generate each module
    for rel_path, content_fn in _FILE_GENERATORS.items():
        file_path = output_dir / rel_path
        file_path.parent.mkdir(parents=True, exist_ok=True)
        content = content_fn(manifest, header)
        file_path.write_text(content, encoding="utf-8")
        generated.append(file_path)

    return generated


