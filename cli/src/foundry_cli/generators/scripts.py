@dataclass(frozen=True)
class DeploymentProfile:
    """Fully-resolved deployment configuration for a single service."""
    name: str
    kind: str
    type: str
    role: str
    strategy: str
    dockerfile: str | None
    build_context: str
    build_command: str | None
    secrets: tuple[SecretMapping, ...]
    cdn: bool | CdnConfig | None
    depends_on: tuple[str, ...]
    sidecars: dict[str, SidecarDeployConfig]
    watch_paths: tuple[str, ...]
    database: str | None

    @property
    def is_deployable(self) -> bool:
        return self.strategy != "none"

    @property
    def needs_docker(self) -> bool:
        return self.strategy == "service"

    @property
    def needs_node(self) -> bool:
        return self.type in ("nextjs", "vite", "react", "vue", "angular")

    @property
    def needs_database_migration(self) -> bool:
        return self.database is not None


STRATEGY_DEFAULTS: dict[tuple[str, str | None], str] = {{
    ("backend", "spring-boot"): "service",
    ("backend", "uvicorn"): "service",
    ("backend", "gunicorn"): "service",
    ("backend", "express"): "service",
    ("backend", "django"): "service",
    ("backend", "flask"): "service",
    ("backend", None): "service",
    ("frontend", "vite"): "static",
    ("frontend", "react"): "static",
    ("frontend", "vue"): "static",
    ("frontend", "angular"): "static",
    ("frontend", "nextjs"): "service",
    ("frontend", None): "service",
    ("package", None): "none",
}}

BUILD_CONTEXT_DEFAULTS: dict[tuple[str, str | None], str] = {{
    ("backend", "spring-boot"): ".",
    ("backend", "uvicorn"): "{{apps_dir}}/backend/{{name}}",
    ("backend", "gunicorn"): "{{apps_dir}}/backend/{{name}}",
    ("backend", "express"): ".",
    ("backend", None): "{{apps_dir}}/backend/{{name}}",
    ("frontend", "nextjs"): ".",
    ("frontend", None): "{{apps_dir}}/frontend/{{name}}",
}}


def resolve_profile(
    name: str,
    service: ServiceConfig,
    structure: StructureConfig,
    databases: dict[str, Any],
) -> DeploymentProfile:
    """Resolve a complete DeploymentProfile from service config + conventions."""
    kind = service.kind or "backend"
    type_ = service.type
    role = service.role or "other"
    deploy = service.deploy or DeployConfig()

    # Resolve database name — inline dict uses service name;
    # string reference to top-level databases block.
    if isinstance(service.database, dict):
        db = name  # Service name IS the logical DB name
    elif isinstance(service.database, str):
        db = service.database
    else:
        db = None

    # Strategy — deploy block > convention default
    _LEGACY = {{"ecs": "service", "s3-static": "static"}}
    raw = (
        (deploy.strategy if deploy else None)
        or STRATEGY_DEFAULTS.get(
            (kind, type_), STRATEGY_DEFAULTS.get((kind, None), "none")
        )
    )
    strategy = _LEGACY.get(raw, raw)

    dockerfile: str | None = None
    if strategy == "service":
        dockerfile = deploy.dockerfile or f"{{structure.apps_dir}}/{{kind}}/{{name}}/Dockerfile"

    ctx_template = BUILD_CONTEXT_DEFAULTS.get(
        (kind, type_), BUILD_CONTEXT_DEFAULTS.get((kind, None), f"{{structure.apps_dir}}/{{kind}}/{{name}}")
    )
    build_context = deploy.build_context or ctx_template.format(
        apps_dir=structure.apps_dir, kind=kind, name=name,
    )

    build_command: str | None = None
    if strategy == "static" and type_ in ("nextjs", "vite", "react", "vue", "angular"):
        build_command = deploy.build_command or "pnpm build"

    sidecars = dict(deploy.sidecars) if deploy.sidecars else {{}}

    if deploy.secrets:
        secrets = deploy.secrets
    else:
        secrets = _default_secrets(kind, type_, role, name, strategy, structure)

    if deploy.cdn is not None:
        cdn = deploy.cdn
    elif strategy == "static":
        cdn = True
    elif kind == "frontend" and strategy == "service":
        cdn = True
    else:
        cdn = False

    if deploy.depends_on:
        depends_on = deploy.depends_on
    else:
        deps: list[str] = ["iac"] if strategy != "none" else []
        if db and db in databases:
            deps.append(f"database:{{db}}")
        for sc_name in sidecars:
            deps.append(f"sidecar:{{sc_name}}")
        depends_on = tuple(deps)

    apps_dir = structure.apps_dir
    packages_dir = structure.packages_dir
    if kind == "backend":
        watch_paths = (f"^{{apps_dir}}/backend/{{name}}/",)
    elif kind == "frontend":
        watch_paths = (f"^{{apps_dir}}/frontend/{{name}}/", f"^{{packages_dir}}/")
    elif kind == "package":
        watch_paths = (f"^{{packages_dir}}/{{name}}/",)
    else:
        watch_paths = ()

    return DeploymentProfile(
        name=name, kind=kind, type=type_ or "other", role=role,
        strategy=strategy, dockerfile=dockerfile, build_context=build_context,
        build_command=build_command, secrets=secrets, cdn=cdn,
        depends_on=depends_on, sidecars=sidecars, watch_paths=watch_paths,
        database=db,
    )


def _default_secrets(
    kind: str, type_: str | None, role: str | None,
    name: str, strategy: str, structure: StructureConfig,
) -> tuple[SecretMapping, ...]:
    if strategy == "none":
        return ()
    apps_dir = structure.apps_dir
    secrets: list[SecretMapping] = []
    if type_ == "spring-boot":
        secrets.append(SecretMapping(
            source="{{prefix}}-{{env}}/microlith-spring-properties",
            target=f"{{apps_dir}}/backend/{{{{service}}}}/src/main/resources/application-{{{{env}}}}.yml",
        ))
        if role == "auth":
            secrets.append(SecretMapping(
                source="{{prefix}}-{{env}}/efga-spring-properties",
                target=f"{{apps_dir}}/backend/{{{{service}}}}/src/main/resources/efga-{{{{env}}}}.yml",
            ))
    elif type_ in ("uvicorn", "gunicorn", "flask", "django"):
        secrets.append(SecretMapping(
            source="{{prefix}}-{{env}}/{{service}}-env",
            target=f"{{apps_dir}}/backend/{{{{service}}}}/.env",
        ))
    elif kind == "frontend":
        secrets.append(SecretMapping(
            source="{{prefix}}-{{env}}/{{service}}-env",
            target=f"{{apps_dir}}/frontend/{{{{service}}}}/.env.production",
        ))
    return tuple(secrets)


def resolve_all_profiles(manifest: Manifest) -> dict[str, DeploymentProfile]:
    """Resolve deployment profiles for all services in a manifest."""
    structure = manifest.structure
    databases = manifest.databases
    profiles: dict[str, DeploymentProfile] = {{}}
    for name, svc in manifest.services.items():
        profiles[name] = resolve_profile(name, svc, structure, databases)
    return profiles
